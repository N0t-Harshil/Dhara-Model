sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from src.data.quality import SimHashDeduplicator, QualityScorer
from src.data.ast_filter import (
    filter_code,
    identifier_ratio,
    executable_ratio,
    is_autogenerated,
    has_one_enormous_line,
    extract_functions,
)
